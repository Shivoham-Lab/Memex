import readline from 'readline';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise(resolve => rl.question(q, resolve));

console.log('\n🚀 Welcome to Memex!\n');
console.log('Memex is a locally hosted MCP server with a web dashboard.');
console.log('It connects multiple AI tools to your codebase securely.\n');

// Step 1: Security
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
console.log('Step 1: Security');
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

const setPassword = await ask('Would you like to set a password? (strongly recommended) [Y/n]: ');
let password = '';
if (setPassword.toLowerCase() !== 'n') {
  password = await ask('Password: ');
  const confirm = await ask('Confirm: ');
  if (password !== confirm) {
    console.error('❌ Passwords do not match. Try again.');
    process.exit(1);
  }
}

// Step 2: Ollama Setup
console.log('\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
console.log('Step 2: Ollama Setup');
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

console.log('Memex uses Ollama for local AI features.\n');
console.log('Choose your mode:\n');
console.log('  [1] Light Mode  — requires nomic-embed-text (274MB, ~2GB RAM)');
console.log('                    Enables: semantic file search');
console.log('                    Requires: ollama pull nomic-embed-text\n');
console.log('  [2] Full Mode   — requires nomic-embed-text + phi4-mini (total ~3GB, ~6GB RAM)');
console.log('                    Enables: semantic search + auto file summaries +');
console.log('                             auto changelog enrichment + smart snapshot updates');
console.log('                    Requires: ollama pull nomic-embed-text');
console.log('                              ollama pull phi4-mini\n');

const modeChoice = await ask('Mode [1/2]: ');
const ollamaMode = modeChoice === '1' ? 'light' : 'full';

// Test Ollama
const ollamaUrl = 'http://localhost:11434';
let ollamaConnected = false;
try {
  const res = await fetch(`${ollamaUrl}/api/tags`);
  ollamaConnected = res.ok;
  if (ollamaConnected) {
    console.log('\n✓ Connected to Ollama');
    const data = await res.json();
    const models = (data.models || []).map(m => m.name);

    if (models.some(m => m.startsWith('nomic-embed-text'))) {
      console.log('✓ nomic-embed-text available');
    } else {
      console.log('✗ nomic-embed-text not found');
      console.log('  Run: ollama pull nomic-embed-text');
    }

    if (ollamaMode === 'full') {
      if (models.some(m => m.startsWith('phi4-mini'))) {
        console.log('✓ phi4-mini available');
      } else if (models.some(m => m.startsWith('gemma3'))) {
        console.log('✓ gemma3 available (using as alternative)');
      } else {
        console.log('✗ phi4-mini not found');
        console.log('  Run: ollama pull phi4-mini');
        console.log('  (You can continue setup and install it later)');
      }
    }
  }
} catch {
  console.log('\n⚠️  Ollama is not running or not accessible at ' + ollamaUrl);
  console.log('   Memex will work without Ollama features.');
  console.log('   Start Ollama and run: ollama pull nomic-embed-text');
}

// Step 3: Generate Secret Key
console.log('\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
console.log('Step 3: Generate Secret Key');
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

const secretKey = crypto.randomBytes(32).toString('hex');
console.log('✓ Generated secure secret key');

// Write .env file
const envContent = `# Memex Environment Configuration
# Generated by init script on ${new Date().toISOString()}

# Authentication (dashboard + MCP connections)
${password ? `MEMEX_PASSWORD=${password}` : '# MEMEX_PASSWORD=yourpassword'}

# JWT signing key (auto-generated, do not share)
MEMEX_SECRET_KEY=${secretKey}

# Server port
PORT=3000

# Ollama configuration
OLLAMA_URL=${ollamaUrl}
OLLAMA_MODE=${ollamaMode}
OLLAMA_THINKING_MODEL=phi4-mini
`;

fs.writeFileSync(ENV_PATH, envContent);
console.log('✓ .env file created');

// Summary
console.log('\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━');
console.log('Setup complete!');
console.log('━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n');

console.log('Next steps:');
console.log('  1. Run: npm install');
console.log('  2. Run: npm run build (builds the dashboard)');
console.log('  3. Run: npm start (starts Memex on port 3000)');
console.log('  4. Run: cloudflared tunnel --url http://localhost:3000');
console.log('  5. Visit your Cloudflare URL to create your first project');
console.log('  6. Copy the MCP URL and add it to your AI tool\n');

console.log('For more details, see README.md\n');

rl.close();
