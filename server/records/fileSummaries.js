import fs from 'fs';
import path from 'path';

/** Read the files summary file */
export function readFileSummaries(projectPath) {
  const filePath = path.join(projectPath, 'memex_files.md');
  if (!fs.existsSync(filePath)) return '';
  return fs.readFileSync(filePath, 'utf-8');
}

/** Write/update the files summary file */
export function writeFileSummaries(projectPath, content) {
  const filePath = path.join(projectPath, 'memex_files.md');
  fs.writeFileSync(filePath, content, 'utf-8');
}

/** Parse memex_files.md into structured entries */
export function parseFileSummaries(content) {
  if (!content) return [];

  const entries = [];
  const blocks = content.split(/^### /m).filter(e => e.trim());

  for (const block of blocks) {
    const lines = block.split('\n');
    const filePath = lines[0].trim();

    const entry = { path: filePath, purpose: '', exports: [], dependsOn: [], lastModifiedBy: '', lastModified: '', ollamaEnhanced: false, gotchas: [] };

    let currentField = '';
    for (const line of lines) {
      if (line.startsWith('**Purpose:**')) {
        entry.purpose = line.replace('**Purpose:**', '').trim();
      } else if (line.startsWith('**Exports:**')) {
        currentField = 'exports';
        const inline = line.replace('**Exports:**', '').trim();
        if (inline) entry.exports.push(inline);
      } else if (line.startsWith('**Depends on:**')) {
        entry.dependsOn = line.replace('**Depends on:**', '').split(',').map(d => d.trim()).filter(Boolean);
      } else if (line.startsWith('**Last modified:**')) {
        const match = line.replace('**Last modified:**', '').trim().match(/(.+) by (.+)/);
        if (match) {
          entry.lastModified = match[1];
          entry.lastModifiedBy = match[2];
        }
      } else if (line.startsWith('**Ollama summary:**')) {
        entry.ollamaEnhanced = true;
      } else if (line.startsWith('**Gotchas:**')) {
        currentField = 'gotchas';
      } else if (currentField === 'exports' && line.startsWith('  - ')) {
        entry.exports.push(line.trim().replace(/^- /, ''));
      } else if (currentField === 'gotchas' && line.startsWith('  - ')) {
        entry.gotchas.push(line.trim().replace(/^- /, ''));
      } else if (line.startsWith('---') || line.startsWith('**')) {
        currentField = '';
      }
    }

    entries.push(entry);
  }

  return entries;
}

/** Get summary entry for a specific file */
export function getFileSummary(projectPath, filePath) {
  const content = readFileSummaries(projectPath);
  const entries = parseFileSummaries(content);
  return entries.find(e => e.path === filePath) || null;
}

/** Update or add a file summary entry */
export function updateFileSummary(projectPath, filePath, updates) {
  let content = readFileSummaries(projectPath);
  const entries = parseFileSummaries(content);
  const existingIndex = entries.findIndex(e => e.path === filePath);

  const entry = existingIndex >= 0 ? entries[existingIndex] : {
    path: filePath, purpose: '', exports: [], dependsOn: [],
    lastModifiedBy: '', lastModified: '', ollamaEnhanced: false, gotchas: []
  };

  Object.assign(entry, updates);

  if (existingIndex >= 0) {
    entries[existingIndex] = entry;
  } else {
    entries.push(entry);
  }

  // Rebuild file
  const newContent = entries.map(e => {
    let block = `### ${e.path}\n`;
    block += `**Purpose:** ${e.purpose || 'No description yet'}\n`;
    block += `**Exports:**\n`;
    if (e.exports.length) {
      block += e.exports.map(ex => `  - ${ex}`).join('\n') + '\n';
    } else {
      block += `  - (none documented)\n`;
    }
    block += `**Depends on:** ${e.dependsOn.join(', ') || 'none documented'}\n`;
    block += `**Last modified:** ${e.lastModified || 'unknown'} by ${e.lastModifiedBy || 'unknown'}\n`;
    if (e.ollamaEnhanced) block += `**Ollama summary:** Generated by Phi-4 Mini\n`;
    block += `**Gotchas:**\n`;
    if (e.gotchas.length) {
      block += e.gotchas.map(g => `  - ${g}`).join('\n') + '\n';
    } else {
      block += `  - (none)\n`;
    }
    block += `\n---\n`;
    return block;
  }).join('\n');

  writeFileSummaries(projectPath, newContent);
  return entry;
}
